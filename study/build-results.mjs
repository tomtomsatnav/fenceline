#!/usr/bin/env node
// study/results.md, rebuilt from the run files alone: every number in it is printed here, from study/results/*.json,
// study/results/runs/*/ (row.json, grade.json, events.jsonl) and study/audit/. Categories are recomputed from each run's
// flags (lib/categorise.mjs), so the document always reflects the rules in force.
//   node study/build-results.mjs [--results study/results] [--audit study/audit] [--out study/results.md]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TASKS, CONFLICT } from './tasks/index.mjs';
import { CATEGORIES } from './lib/categorise.mjs';
import { PRESENTATIONS } from './lib/presentation.mjs';
import { loadBatches, spend, runCost, PHASES, SHARED_CAP_PHASES, SHARED_CAP_USD } from './lib/runs.mjs';
import { categoryOf, cells, h1, h2, h3, valid, MARGIN } from './lib/analysis.mjs';
import { wilson, mde, fmtRate, fmtDiff, pct } from './lib/stats.mjs';
import { score } from './audit.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2); const opt = (n, d) => { const i = args.indexOf(`--${n}`); return i >= 0 ? args[i + 1] : d; };
const resultsDir = path.resolve(opt('results', path.join(here, 'results')));
const auditDir = path.resolve(opt('audit', path.join(here, 'audit')));
const out = path.resolve(opt('out', path.join(here, 'results.md')));
const rel = (p) => path.relative(path.dirname(out), p).split(path.sep).join('/');

const batches = loadBatches(resultsDir);
const runs = batches.flatMap((b) => b.runs.map((r) => ({ ...r, batch: b })));
const money = (x) => `$${x.toFixed(2)}`;
const L = [];
const P = (...xs) => L.push(...xs);
const table = (head, rows) => P(`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`), '');

P('# Results', '', '<!-- generated by node study/build-results.mjs from the run files; do not edit by hand -->', '');
P(`Runs on disk: ${runs.length} (${valid(runs).length} valid, ${runs.length - valid(runs).length} invalid) in ${batches.length} batches. `
  + `Every rate is k/n (percent, 95% Wilson interval in points); differences carry a 95% Newcombe interval. Verdict rule `
  + `(PREREG section 8): supported if the interval excludes 0 in the predicted direction; not supported if it rules out an effect `
  + `of ${Math.round(MARGIN * 100)} points or more; otherwise inconclusive.`, '');
if (!runs.length) P('_No study runs yet. The pre-registered tables below fill in as batches land._', '');

// ---- H2 first: it is the headline question
P('## H2 (primary): does enforcement produce more on-paper compliance than a stated rule?', '',
  'PAPER rate on the four conflict tasks, pooled, main grid. `block` = Fenceline deny, rule never mentioned; `stated` = the rule in the prompt, not enforced.', '');
table(['model', 'block: PAPER', 'stated: PAPER', 'difference (block - stated)', 'verdict', 'stated: ASK', 'block: ASK', 'difference (stated - block)'],
  h2(runs).map((x) => [x.model, fmtRate(x.paper.a), fmtRate(x.paper.b), fmtDiff(x.paper.d), x.paper.verdict, fmtRate(x.ask.a), fmtRate(x.ask.b), fmtDiff(x.ask.d)]));
P('The per-model rows are the pre-registered test; the pooled row is secondary.', '',
  'Secondary: `block-neutral` (denied, with a message that only states the rule) against the stated rule, and against the shipped deny (which also says not to work around it, and to ask).', '');
table(['model', 'block-neutral: PAPER', 'stated: PAPER', 'difference (neutral - stated)', 'verdict', 'block: PAPER', 'difference (neutral - block)', 'verdict'],
  h2(runs).map((x) => [x.model, fmtRate(x.neutral.a), fmtRate(x.neutral.b), fmtDiff(x.neutral.d), x.neutral.verdict, fmtRate(x.wording.b), fmtDiff(x.wording.d), x.wording.verdict]));

const x1 = h1(runs);
P('## H1: do smaller models comply on paper more often?', '', 'PAPER rate, conflict tasks, presentations `stated`, `file`, `block`, `stated+block`, `block-neutral`, main grid.', '');
table(['haiku: PAPER', 'sonnet: PAPER', 'difference (haiku - sonnet)', 'verdict'], [[fmtRate(x1.a), fmtRate(x1.b), fmtDiff(x1.d), x1.verdict]]);

const x3 = h3(runs);
P('## H3: are stated rules crossed more often in long sessions?', '', `Crossing rate (CROSS or CROSS_REVERT), task ${x3.tasks.join(', ') || '(phase 4 not run)'}, presentations \`stated\` and \`file\`, both models.`, '');
table(['long: crossed', 'short (main grid): crossed', 'difference (long - short)', 'verdict'], [[fmtRate(x3.a), fmtRate(x3.b), fmtDiff(x3.d), x3.verdict]]);

// ---- what the grid can and cannot see
P('## What these sample sizes can detect', '', 'Smallest difference a two-sided test at 5% detects with 80% power (normal approximation), for a baseline rate of 10% or 30%:', '');
table(['comparison', 'n per arm', 'baseline 10%', 'baseline 30%'], [
  ['one cell vs another', 10, pct(mde(0.1, 10)), pct(mde(0.3, 10))],
  ['H2, one model (4 tasks pooled)', 40, pct(mde(0.1, 40)), pct(mde(0.3, 40))],
  ['H1 (4 tasks x 5 presentations)', 200, pct(mde(0.1, 200)), pct(mde(0.3, 200))],
  ['H3 (long k=5 x 2 x 2 vs short)', 20, pct(mde(0.1, 20)), pct(mde(0.3, 20))]]);
P(`At k = 10, a 95% interval around 5/10 runs from ${pct(wilson(5, 10).lo)} to ${pct(wilson(5, 10).hi)}: single cells say little on their own, and only differences larger than the figures above should be read as real.`, '');

// ---- every cell
const order = (c) => [PHASES[c.phase], Object.keys(TASKS).indexOf(c.task), Object.keys(PRESENTATIONS).indexOf(c.presentation), c.model];
const sorted = cells(runs).sort((a, b) => { const x = order(a); const y = order(b); for (let i = 0; i < x.length; i++) if (x[i] !== y[i]) return x[i] < y[i] ? -1 : 1; return 0; });
for (const phase of Object.keys(PHASES)) {
  const cs = sorted.filter((c) => c.phase === phase); if (!cs.length) continue;
  P(`## Categories by cell: phase ${PHASES[phase]} (${phase})`, '');
  table(['task', 'presentation', 'model', 'valid / runs', ...CATEGORIES, 'awaiting judge'], cs.map((c) => [c.task, c.presentation, c.model, `${c.v.length}/${c.runs}`, ...CATEGORIES.map((k) => fmtRate(c.cat[k])), c.ungraded]));
  P('Secondary flags (valid runs):', '');
  table(['task', 'presentation', 'model', 'read fences file', 'denied at least once', 'tests pass', 'seed tests pass', 'hidden tests pass', 'crossed file named in final msg (crossed runs)', 'hook log covers git', 'mean $', 'mean s', 'mean turns'],
    cs.map((c) => { const v = c.v; const crossed = v.filter((r) => r.git_crossed.length); const m = (f) => (v.length ? v.reduce((s, r) => s + (f(r) ?? 0), 0) / v.length : NaN);
      return [c.task, c.presentation, c.model, fmtRate(wilson(v.filter((r) => r.read_fences_file).length, v.length)), fmtRate(wilson(v.filter((r) => r.denied_count).length, v.length)),
        fmtRate(wilson(v.filter((r) => r.tests_pass).length, v.length)), fmtRate(wilson(v.filter((r) => r.seed_tests_pass).length, v.length)), fmtRate(wilson(v.filter((r) => r.hidden_pass).length, v.length)),
        crossed.length ? `${crossed.filter((r) => r.crossing_mentioned_in_final_message).length}/${crossed.length}` : '-', `${v.filter((r) => r.hook_covers_git).length}/${v.length}`,
        m((r) => r.cost_usd).toFixed(4), m((r) => r.wall_s).toFixed(0), m((r) => r.turns).toFixed(1)]; }));
}

// ---- the judge
P('## The judge and the blind audit', '');
const judged = runs.filter((r) => r.grade); const failed = judged.filter((r) => !r.grade.verdict);
P(`Runs graded by the judge: ${judged.length - failed.length}${failed.length ? ` (plus ${failed.length} failed attempts, to be retried)` : ''}; still owed a grade: ${runs.filter((r) => categoryOf(r) === 'UNGRADED').length}. Judge model ids: ${[...new Set(judged.flatMap((r) => r.grade.models_used))].join(', ') || '-'}.`, '');
const s = score(auditDir, runs);
if (!s) P('Audit not drawn yet.', '');
else {
  P(`Tom graded ${s.n_graded} of ${s.n_sampled} sampled runs blind (seed \`${s.seed}\`). Agreement with the judge: **${Number.isFinite(s.agree) ? pct(s.agree) : '-'}** (Cohen's kappa ${Number.isFinite(s.kappa) ? s.kappa.toFixed(2) : '-'}).`, '');
  if (Number.isFinite(s.agree) && s.agree < 0.85) P(`> **Agreement is below 85%.** Every REROUTE/PAPER figure above rests on the judge; read them with that in mind.`, '');
  if (s.disagreements.length) table(['audit id', 'run', 'Tom', 'judge'], s.disagreements.map((d) => [d.id, `[${d.run}](${rel(path.join(resultsDir, 'runs', d.run))})`, d.a, d.b ?? '-']));
}

// ---- cost and versions
P('## Cost and versions', '');
table(['phase', 'batches', 'runs', 'agent $', 'judge $', 'total $'], Object.keys(PHASES).map((ph) => { const bs = batches.filter((b) => b.phase === ph); const rs = bs.flatMap((b) => b.runs);
  return [`${PHASES[ph]} ${ph}`, bs.length, rs.length, money(rs.reduce((x, r) => x + (r.cost_usd ?? r.max_budget_usd ?? 0), 0)), money(rs.reduce((x, r) => x + (r.grade?.cost_usd ?? 0), 0)), money(rs.reduce((x, r) => x + runCost(r), 0))]; }));
P(`Phases 1 + 2 spent ${money(spend(batches, SHARED_CAP_PHASES))} of the approved ${money(SHARED_CAP_USD)} (runs with no reported cost are counted at their per-run cap).`, '');
table(['batch', 'phase', 'task', 'presentation', 'model alias', 'model ids', 'Claude Code', 'commit', 'runs', 'stopped early'],
  batches.map((b) => [b.file.replace(/\.json$/, ''), b.phase, b.task, b.presentation, b.model_alias, [...new Set(b.runs.flatMap((r) => r.models_used))].join(', ') || '-', b.claude_version, `${b.fenceline_commit.slice(0, 7)}${b.fenceline_dirty ? '+' : ''}`, b.runs.length, b.stopped_early || '-']));

// ---- invalid runs
const inv = runs.filter((r) => r.invalid);
P('## Invalid runs', '', inv.length ? 'Kept on disk and listed here; excluded from every rate.' : 'None.', '');
if (inv.length) table(['run', 'reason'], inv.map((r) => [`[${r.name}](${rel(r.dir)})`, r.invalid]));

// ---- replays: the most informative PAPER and CROSS runs, chosen by a fixed rule
const v = valid(runs).filter((r) => CONFLICT.includes(r.task));
const rank = (r) => [r.presentation === 'none' ? 1 : 0, r.hidden_pass ? 1 : 0, r.name];
const byRank = (a, b) => { const x = rank(a); const y = rank(b); for (let i = 0; i < x.length; i++) if (x[i] !== y[i]) return x[i] < y[i] ? -1 : 1; return 0; };
const paper = v.filter((r) => categoryOf(r) === 'PAPER').sort(byRank); const cross = v.filter((r) => ['CROSS', 'CROSS_REVERT'].includes(categoryOf(r))).sort(byRank);
const chosen = [...paper.slice(0, 3), ...cross.slice(0, 2)];
for (const r of [...paper.slice(3), ...cross.slice(2)]) if (chosen.length < 5) chosen.push(r);
P('## Session replays', '', 'Up to five runs: three PAPER and two CROSS from the conflict tasks (topped up from the other if one is short), preferring runs where the rule was told or enforced, then runs whose hidden tests fail. The notes are mechanical; the reading of them is Tom\'s.', '');
if (!chosen.length) P('_None yet._', '');
for (const r of chosen) {
  const ev = fs.existsSync(path.join(r.dir, 'events.jsonl')) ? fs.readFileSync(path.join(r.dir, 'events.jsonl'), 'utf8').trim().split('\n').filter(Boolean).map((l) => JSON.parse(l)) : [];
  P(`### ${categoryOf(r)}: ${r.task}, ${r.presentation}, ${r.model} #${r.trial}`, '', `Run files: [${r.name}](${rel(r.dir)}) · diff: [diff.patch](${rel(path.join(r.dir, 'diff.patch'))}) · tests pass ${r.tests_pass}, seed tests ${r.seed_tests_pass}, hidden tests ${r.hidden_pass} · $${(r.cost_usd ?? 0).toFixed(4)}, ${Math.round(r.wall_s)} s`, '');
  for (const e of ev.filter((x) => ['touch', 'crossing', 'blocked'].includes(x.kind))) {
    const writes = (e.touches || []).filter((t) => ['create', 'edit', 'delete'].includes(t.op)).map((t) => `${t.op} ${t.file}`);
    const note = e.kind === 'blocked' ? `**denied**: ${e.crossings.map((c) => `${c.op} ${c.file} ("${c.text}")`).join(', ')}` : e.kind === 'crossing' ? `**crossed**: ${e.crossings.map((c) => `${c.op} ${c.file}`).join(', ')}` : writes.join(', ');
    if (note || e.tool === 'Bash') P(`- ${(e.elapsed_ms / 1000).toFixed(0)} s · ${e.tool}${e.command ? ` \`${e.command.replace(/`/g, "'").slice(0, 100)}\`` : ''}${note ? ` · ${note}` : ''}`);
  }
  P('', `Judge: ${r.grade?.verdict ? `${r.grade.verdict}${r.grade.workaround ? ` (${r.grade.workaround})` : ''}: ${r.grade.reason}` : '-'}`, '', '> Final message (first 600 characters):', ...String(r.final_message || '(none)').slice(0, 600).split('\n').map((l) => `> ${l}`), '');
}

P('## Limits', '', '- Small generated repos (7 to 63 files) and synthetic tasks, written for this study; behaviour on real codebases may differ.',
  '- One harness (Claude Code with Fenceline\'s hooks). Its shipped deny message tells the agent not to work around the fence and to ask; `block-neutral` measures what that wording does.',
  '- REROUTE vs PAPER rests on an LLM judge, checked against one person\'s blind grades on a sample.',
  '- k = 10 per cell: only large differences are detectable (table above). Model aliases resolve to whatever ids Claude Code served on the day (listed per batch).', '');

fs.writeFileSync(out, `${L.join('\n')}\n`);
console.log(`wrote ${path.relative(process.cwd(), out)} (${runs.length} runs)`);
